const sides = { _l: '左', _r: '右' }

export function localizeStructure(structure) {
    const side = sides[structure.key.slice(-2)]
    const name = names[side ? structure.key.slice(0, -2) : structure.key]
    const [categoryLabel, categoryColor] = categories[structure.category] ?? ['其他结构', '#5b6b86']
    return {
        ...structure,
        displayName: name ? `${side ?? ''}${name}` : '未命名结构',
        categoryLabel,
        categoryColor,
    }
}
